#!/usr/bin/env python3
"""Extract authored primitive tables from one pinned upstream source file, never captures."""
import argparse
import hashlib
from pathlib import Path
import re

UPSTREAM_SHA256='12d075f84ab5d6662823a9dcd4cc28abe1126ab2b7df536c811c23c37fc0878f'
COMMIT='e13b728c6880d3084d9d57c30031ed5df8b39dee'


def render(source):
    assert hashlib.sha256(source).hexdigest()==UPSTREAM_SHA256,'wrong source bytes'
    source=source.decode()
    blocks=[]
    for upstream,name,kind,width,count in [
        ('icovert','ICO_VERTICES','f32',3,12),('icoface','ICO_FACES','usize',3,20),
        ('icouvs','ICO_UVS','f32',2,60),('monkeyv','MONKEY_VERTICES','i8',3,271),
        ('monkeyf','MONKEY_FACES','i8',4,250),('monkeyuvs','MONKEY_UVS','f32',2,1968)]:
        match=re.search(r'static (?:const )?(?:float|short|signed char) '+upstream+r'(?:\[[^\]]*\])+\s*=\s*\{(.*?)\};',source,re.S)
        assert match,upstream
        numbers=re.findall(r'[-+]?(?:\d+\.\d*|\d*\.\d+|\d+)(?:[eE][-+]?\d+)?f?',match[1])
        numbers=[token.removesuffix('f') for token in numbers]
        assert len(numbers)==width*count,(upstream,len(numbers))
        if kind=='f32':numbers=[token if '.' in token or 'e' in token.lower() else token+'.0' for token in numbers]
        else:assert all(-128<=int(token)<=127 for token in numbers)
        lines=[f'pub(super) const {name}: [[{kind}; {width}]; {count}] = [']
        lines.extend('    ['+', '.join(numbers[i:i+width])+'],' for i in range(0,len(numbers),width))
        lines.append('];');blocks.append('\n'.join(lines))
    return ('// SPDX-FileCopyrightText: 2023 Blender Authors\n'
            '// SPDX-License-Identifier: GPL-2.0-or-later\n'
            '// Authored source tables, not measured reference geometry.\n'
            f'// Upstream commit: {COMMIT}\n'
            f'// bmo_primitive.cc SHA-256: {UPSTREAM_SHA256}\n'
            '// Generated by tools/generate_legacy_primitive_tables.py.\n\n'+'\n\n'.join(blocks)+'\n')


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('upstream',type=Path);parser.add_argument('output',type=Path)
    args=parser.parse_args();args.output.write_text(render(args.upstream.read_bytes()))


if __name__=='__main__':main()
